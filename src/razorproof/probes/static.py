def _source_evidence(repo: Repository, relative: str, needle: str, summary: str) -> Evidence:
    text = read(repo.path / relative)
    return Evidence(
        kind="official_source",
        summary=summary,
        detail=needle,
        path=f"{repo.name}/{relative}",
        line=line_number(text, needle),
        source_url=f"{repo.remote.removesuffix('.git')}/blob/{repo.commit}/{relative}",
    )


