def _dotnet(repo: Repository) -> list[Finding]:
    relative = "src/Utils.cs"
    source = read(repo.path / relative)
    findings: list[Finding] = []
    if "new ASCIIEncoding()" in source:
        findings.append(Finding(
            id="RP-DOTNET-WEBHOOK-ASCII",
            title=".NET webhook verifier hashes non-ASCII strings as ASCII",
            repo=repo.name,
            surface="Utils.verifyWebhookSignature",
            invariant="HMAC input is the exact UTF-8 request body, byte for byte.",
            severity=Severity.MEDIUM,
            level=EvidenceLevel.STATIC,
            confidence=1.0,
            originality="independently discovered; no matching public report found",
            commit=repo.commit,
            description="The SDK's central StringEncode helper is ASCIIEncoding, so names, notes, and descriptions in Indian scripts or emoji become question marks.",
            impact="A correct UTF-8 signature is rejected for ordinary Razorpay Test Mode payment-link and refund deliveries containing literal non-ASCII metadata.",
            counterexample='payload={"name":"Achu ₹ മലയാളം"}: Razorpay signs UTF-8; SDK hashes ASCII substitutions.',
            proposed_fix="Expose a byte[] webhook API and use UTF-8 explicitly for string compatibility overloads.",
            evidence=[_source_evidence(repo, relative, "new ASCIIEncoding()", "All signature strings are encoded as ASCII")],
            tags=["webhook", "unicode", "cryptography", "dotnet"],
            claim_kind=ClaimKind.DEFECT,
        ))
    if "Array.Copy(keyBytes, 0, iv, 0, 12)" in source:
        findings.append(Finding(
            id="RP-DOTNET-GCM-NONCE-REUSE",
            title=".NET onboarding signatures reuse an AES-GCM nonce derived from the secret key",
            repo=repo.name,
            surface="Utils.GenerateOnboardingSignature",
            invariant="AES-GCM uses a fresh unique nonce for every encryption under a key.",
            severity=Severity.CRITICAL,
            level=EvidenceLevel.STATIC,
            confidence=1.0,
            originality="independently discovered cross-SDK regression; Ruby, Node, Java and PHP already shipped the random-nonce fix",
            commit=repo.commit,
            description="The first 12 key bytes are copied into the IV, making every encryption under one secret reuse the same GCM nonce.",
            impact="Nonce reuse breaks AES-GCM confidentiality and authentication guarantees; repeated onboarding signatures become deterministic and related plaintexts leak keystream relations.",
            counterexample="Encrypting identical onboarding JSON twice under one secret returns identical ciphertext.",
            proposed_fix="Generate 12 random bytes per call and return nonce || ciphertext || 16-byte tag, matching the other current SDKs.",
            evidence=[
                _source_evidence(repo, relative, "Array.Copy(keyBytes, 0, iv, 0, 12)", "IV is deterministically copied from the key"),
                Evidence(kind="cross_sdk_release", summary="Ruby release documents the same nonce-reuse defect and fixed wire format", source_url="https://github.com/razorpay/razorpay-ruby/releases/tag/v3.2.4"),
            ],
            tags=["cryptography", "aes-gcm", "nonce-reuse", "cross-sdk"],
        ))
    if "actualSignature.Equals(expectedSignature)" in source:
        findings.append(Finding(
            id="RP-DOTNET-SIGNATURE-COMPARE",
            title=".NET signature verification uses ordinary string equality",
            repo=repo.name,
            surface="Utils.verifySignature",
            invariant="Authentication tags are compared in constant time.",
            severity=Severity.LOW,
            level=EvidenceLevel.KNOWN,
            confidence=0.98,
            originality="publicly proposed hardening and independently source-confirmed; no practical remote exploit reproduced",
            commit=repo.commit,
            description="The verifier uses String.Equals rather than a fixed-time byte comparison.",
            impact="Ordinary equality is functionally correct. A fixed-time comparison reduces timing leakage, but practical remote exploitability was not reproduced or claimed.",
            proposed_fix="Decode hex and call CryptographicOperations.FixedTimeEquals.",
            known_reference="https://github.com/razorpay/razorpay-dot-net/pull/153",
            evidence=[_source_evidence(repo, relative, "actualSignature.Equals(expectedSignature)", "Non-constant-time comparison")],
            tags=["cryptography", "timing", "dotnet"],
            claim_kind=ClaimKind.HARDENING,
        ))

    client_relative = "src/RazorpayClient.cs"
    client_source = read(repo.path / client_relative)
    rest_relative = "src/RestClient.cs"
    rest_source = read(repo.path / rest_relative)
    if (
        "private static string key" in client_source
        and "private static string secret" in client_source
        and "RazorpayClient.Key" in rest_source
        and "RazorpayClient.Secret" in rest_source
    ):
        findings.append(Finding(
            id="RP-DOTNET-GLOBAL-AUTH-STATE",
            title=".NET client instances overwrite one process-wide credential and routing context",
            repo=repo.name,
            surface="RazorpayClient, RestClient, and payment signature verification",
            invariant="Credentials, base URL, access token, and request headers are scoped to one client instance and cannot be changed by constructing another client.",
            severity=Severity.HIGH,
            level=EvidenceLevel.STATIC,
            confidence=1.0,
            originality="independently discovered; no matching public issue or pull request found",
            commit=repo.commit,
            description="The public client stores key, secret, base URL, access token, application details, and headers in static fields. Constructors overwrite them, while requests and payment verification read those global fields later.",
            impact="A multi-tenant or multi-account .NET process can authenticate client A's request as client B, route it with another account's X-Razorpay-Account header, or reject A's valid payment signature after B is initialized.",
            counterexample="Construct client A, then client B; client A's subsequent request and Utils.verifyPaymentSignature use B's static key/secret.",
            proposed_fix="Make all authentication, endpoint, header, and utility state immutable instance fields; bind resource clients and verification calls to an explicit client or secret.",
            evidence=[
                _source_evidence(repo, client_relative, "private static string key = null;", "API key is process-global"),
                _source_evidence(repo, client_relative, "private static string secret = null;", "API secret is process-global"),
                _source_evidence(repo, client_relative, "protected static Dictionary<string, string> headers", "Partner routing and custom headers are process-global"),
                _source_evidence(repo, rest_relative, "string authString = string.Format(\"{0}:{1}\", RazorpayClient.Key, RazorpayClient.Secret);", "Every request reads current global credentials"),
                _source_evidence(repo, relative, "string secret = RazorpayClient.Secret;", "Payment verification reads the current global secret"),
            ],
            tags=["security", "multi-tenant", "credentials", "partner-routing", "dotnet", "global-state"],
        ))
    return findings


