def run_static_probes(repositories: dict[str, Repository]) -> list[ProbeResult]:
    results: list[ProbeResult] = []
    with ProbeTimer("static:mcp-semantic-contracts") as result:
        if repo := repositories.get("razorpay-mcp-server"):
            result.findings.extend(_mcp(repo))
        else:
            result.errors.append("razorpay-mcp-server repository missing")
    results.append(result)
    with ProbeTimer("static:sdk-cryptographic-contracts") as result:
        if repo := repositories.get("razorpay-dot-net"):
            result.findings.extend(
                finding for finding in _dotnet(repo)
                if finding.id != "RP-DOTNET-GLOBAL-AUTH-STATE"
            )
        if repo := repositories.get("razorpay-ruby"):
            result.findings.extend(_ruby(repo))
        if repo := repositories.get("razorpay-python"):
            result.findings.extend(_python(repo))
        result.findings.extend(_other_crypto(repositories))
    results.append(result)
    with ProbeTimer("static:sdk-client-and-multipart-contracts") as result:
        if repo := repositories.get("razorpay-dot-net"):
            result.findings.extend(
                finding for finding in _dotnet(repo)
                if finding.id == "RP-DOTNET-GLOBAL-AUTH-STATE"
            )
        if repo := repositories.get("razorpay-php"):
            result.findings.extend(_php(repo))
        if repo := repositories.get("razorpay-java"):
            result.findings.extend(_java_semantics(repo))
    results.append(result)
    return results
